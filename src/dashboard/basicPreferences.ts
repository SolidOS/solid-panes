export const basicPreferencesPane: PaneDefinition = {
  icon: icons.iconBase + 'noun_Sliders_341315_000000.svg',
  name: 'basicPreferences',
  label: _subject => {
    return null
  },

  // Render the pane
  // The subject should be the logged in user.
  render: (subject, context) => {
    const dom = context.dom
    // @ts-ignore
    const store = context.session.store as Store

    function complainIfBad (ok: Boolean, mess: any) {
      if (ok) return
      main.appendChild(widgets.errorMessageBlock(dom, mess, '#fee'))
    }

    // Two columns, as in the design: the sections, and Help & Support beside them
    const container = dom.createElement('div')
    container.setAttribute('style', styles.layout)
    const main = container.appendChild(dom.createElement('div'))
    main.setAttribute('style', styles.mainColumn)
    addHelpSection(container, dom)

    const formArea = setupUserTypesSection(main, dom)

    function loadData (doc: NamedNode, turtle: String) {
      doc = doc.doc() // remove # from URI if nec
      if (!store.holds(undefined, undefined, undefined, doc)) {
        // If not loaded already
        ;(parse as any)(turtle, store, doc.uri, 'text/turtle', null) // Load form directly
      }
    }

    const preferencesForm = store.sym(
      'urn:uuid:93774ba1-d3b6-41f2-85b6-4ae27ffd2597#this'
    )
    loadData(preferencesForm, preferencesFormText)

    const ontologyExtra = store.sym(
      'urn:uuid:93774ba1-d3b6-41f2-85b6-4ae27ffd2597-ONT'
    )
    loadData(ontologyExtra, ontologyData)

    async function doRender () {
      const renderContext = await login.ensureLoadedPreferences({
        dom,
        div: container
      })
      if (!renderContext.preferencesFile) {
        // Could be CORS
        console.log(
          'Not doing private class preferences as no access to preferences file. ' +
          renderContext.preferencesFileError
        )
        return
      }
      const appendedForm = widgets.appendForm(
        dom,
        formArea,
        {},
        renderContext.me,
        preferencesForm,
        renderContext.preferencesFile,
        complainIfBad
      )
      styleForm(appendedForm, dom)

      const trustedApplicationsView = context.session.paneRegistry.byName('trustedApplications')
      if (trustedApplicationsView) {
        main.appendChild(trustedApplicationsView.render(null, context))
      }

      // @@ TODO Remove need for casting as any and bang (!) syntax
      addDeleteSection(main, store, renderContext.me!, dom)
    }

    doRender()

    return container
  }
}

function setupUserTypesSection (
  container: Element,
  dom: HTMLDocument
): Element {
  const formContainer = createSection(container, dom, 'User types')

  const description = formContainer.appendChild(dom.createElement('p'))
  description.setAttribute('style', styles.description)
  description.textContent = 'The options presented to you when viewing data can be customised based on your role. '

  const userTypesLink = description.appendChild(dom.createElement('a'))
  userTypesLink.href = 'https://github.com/solidos/userguide/#role'
  userTypesLink.textContent = 'Read more'

  const formArea = formContainer.appendChild(dom.createElement('div'))

  return formArea
}

/**
 * The form is generated by solid-ui with its own inline styles.
 * Restyle the generated elements to match the Preferences design.
 */
function styleForm (form: HTMLElement, dom: HTMLDocument): void {
  form.style.border = 'none'
  form.style.paddingLeft = '0'
  form.querySelectorAll<HTMLElement>('.formFieldName').forEach(label => {
    label.setAttribute('style', styles.fieldLabel)
    label.querySelectorAll('a').forEach(link => link.setAttribute('style', 'color: inherit; text-decoration: none;'))
    label.appendChild(infoIcon(dom, 'Power users and developers are offered extra views of their data. This is private, and stored in your preferences file.'))
  })
  form.querySelectorAll('select').forEach(select => select.setAttribute('style', styles.select))
}

export default basicPreferencesPane

