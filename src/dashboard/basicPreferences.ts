function addDeleteSection (
  container: HTMLElement,
  store: IndexedFormula,
  profile: NamedNode,
  dom: HTMLDocument
): void {
  const section = createSection(container, dom, 'Delete your Solid account',
    'Account deletion is handled by your Pod provider. You will be taken to their site to confirm.')

  const description = section.appendChild(dom.createElement('p'))
  description.setAttribute('style', styles.description)
  description.textContent = 'If you no longer want your Solid Pod, you can delete your account.'

  const warning = section.appendChild(dom.createElement('div'))
  warning.setAttribute('style', styles.warning)
  warning.setAttribute('role', 'note')
  const warningIcon = warning.appendChild(dom.createElement('icon-lucide-triangle-alert'))
  warningIcon.setAttribute('aria-hidden', 'true')
  warningIcon.setAttribute('style', 'flex: 0 0 16px; width: 16px; height: 16px; margin-top: 2px;')
  const warningText = warning.appendChild(dom.createElement('div'))
  const warningTitle = warningText.appendChild(dom.createElement('strong'))
  warningTitle.setAttribute('style', 'font-weight: 500;')
  warningTitle.textContent = 'Warning:'
  const warningBody = warningText.appendChild(dom.createElement('p'))
  warningBody.setAttribute('style', 'margin: 8px 0 0; color: var(--color-text-secondary, #4a5565);')
  warningBody.textContent = 'When your account is deleted, all of the data is deleted and cannot be restored.'

  const podServerNodes = store.each(profile, ns.space('storage'), null, profile.doc())
  const podServers = podServerNodes.map(node => node.value)

  const list = section.appendChild(dom.createElement('div'))
  list.setAttribute('style', 'display: flex; flex-wrap: wrap; gap: 8px;')

  podServers.forEach(async server => {
    const deletionLink = await generateDeletionLink(server, dom)
    if (deletionLink) {
      list.appendChild(deletionLink)
    }
  })
}

async function generateDeletionLink (
  podServer: string,
  dom: HTMLDocument
): Promise<HTMLElement | null> {
  const link = dom.createElement('a')
  link.setAttribute('style', styles.dangerButton)
  link.setAttribute('title', `Delete your account at ${podServer}`)
  const icon = link.appendChild(dom.createElement('icon-lucide-trash-2'))
  icon.setAttribute('aria-hidden', 'true')
  icon.setAttribute('style', 'width: 14px; height: 14px;')
  link.appendChild(dom.createTextNode('Delete your account'))
  const deletionUrl = await getDeletionUrlForServer(podServer)
  if (typeof deletionUrl !== 'string') {
    return null
  }
  link.href = deletionUrl
  return link
}

/**
 * Hacky way to get the deletion link to a Pod
 *
 * This function infers the deletion link by assuming the URL structure of Node Solid server.
 * In the future, Solid will hopefully provide a standardised way of discovering the deletion link:
 * https://github.com/solidos/data-interoperability-panel/issues/18
 *
 * If NSS is in multi-user mode (the case on inrupt.net and solid.community), the deletion URL for
 * vincent.dev.inrupt.net would be at dev.inrupt.net/account/delete. In single-user mode, the
 * deletion URL would be at vincent.dev.inrupt.net/account/delete.
 *
 * @param server Pod server containing the user's account.
 * @returns URL of the page that Node Solid Server would offer to delete the account, or null if
 *          the URLs we tried give invalid responses.
 */
async function getDeletionUrlForServer (
  server: string
): Promise<string | null> {
  const singleUserUrl = new URL(server)
  const multiUserUrl = new URL(server)
  multiUserUrl.pathname = singleUserUrl.pathname = '/account/delete'

  const hostnameParts = multiUserUrl.hostname.split('.')
  // Remove `vincent.` from `vincent.dev.inrupt.net`, for example:
  multiUserUrl.hostname = hostnameParts.slice(1).join('.')

  const multiUserNssResponse = await fetch(multiUserUrl.href, {
    method: 'HEAD'
  })
  if (multiUserNssResponse.ok) {
    return multiUserUrl.href
  }

  const singleUserNssResponse = await fetch(singleUserUrl.href, {
    method: 'HEAD'
  })
  if (singleUserNssResponse.ok) {
    return singleUserUrl.href
  }
  return null
}

function createSection (
  container: Element,
  dom: HTMLDocument,
  title: string,
  info?: string
): Element {
  const section = container.appendChild(dom.createElement('div'))
  section.setAttribute('style', styles.card)

  const titleElement = section.appendChild(dom.createElement('h3'))
  titleElement.setAttribute('style', styles.cardTitle)
  titleElement.textContent = title
  if (info) titleElement.appendChild(infoIcon(dom, info))

  return section
}

function addHelpSection (container: Element, dom: HTMLDocument): void {
  const aside = container.appendChild(dom.createElement('aside'))
  aside.setAttribute('style', styles.aside)
  const section = aside.appendChild(dom.createElement('div'))
  section.setAttribute('style', styles.card + ' padding: 16px;')

  const title = section.appendChild(dom.createElement('h3'))
  title.setAttribute('style', 'margin: 0 0 8px; font-size: 1rem; font-weight: 600;')
  title.textContent = 'Help & Support'

  const text = section.appendChild(dom.createElement('p'))
  text.setAttribute('style', styles.description)
  text.textContent = 'Your preferences are stored privately in your Pod. Trusted applications are listed in your profile. '
  const link = text.appendChild(dom.createElement('a'))
  link.href = 'https://solidos.github.io/userguide/'
  link.target = '_blank'
  link.rel = 'noopener noreferrer'
  link.textContent = 'SolidOS user guide'
}

/** A small (i) icon whose tooltip explains a section or field */
export function infoIcon (dom: HTMLDocument, text: string): HTMLElement {
  const span = dom.createElement('span')
  span.setAttribute('role', 'img')
  span.setAttribute('aria-label', text)
  span.setAttribute('title', text)
  span.setAttribute('tabindex', '0')
  span.setAttribute('style', 'display: inline-flex; width: 16px; height: 16px; color: var(--color-text-secondary, #4a5565); cursor: help;')
  const icon = span.appendChild(dom.createElement('icon-lucide-info'))
  icon.setAttribute('aria-hidden', 'true')
  icon.setAttribute('style', 'width: 16px; height: 16px;')
  return span
}

